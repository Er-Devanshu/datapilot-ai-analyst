from __future__ import annotations

from dataclasses import dataclass

from datapilot.llm.local import LocalLLM
from datapilot.llm.prompts import SQLPromptBuilder


@dataclass(frozen=True)
class SQLRepairResult:
    """Result returned by the SQL repair process."""

    question: str
    original_sql: str
    repaired_sql: str
    model_name: str


class SQLRepairer:
    """Repair invalid SQL using LLM feedback."""

    REPAIR_INSTRUCTIONS = """
You are repairing a SQL query generated by DataPilot.

The previous SQL query failed validation.

Your task is to produce a corrected DuckDB SQL query.

Rules:

1. Return exactly one SQL statement.
2. Return read-only SQL only.
3. Use only tables and columns present in the schema.
4. Follow the business metric definitions exactly.
5. Fix the specific validation errors provided.
6. Preserve the original analytical intent.
7. Do not invent schema elements.
8. Do not use INSERT, UPDATE, DELETE, DROP, ALTER, CREATE,
   TRUNCATE, MERGE, or other write operations.
9. Return only the corrected SQL.
10. Do not use Markdown code fences.
11. Do not provide explanations.
""".strip()

    def __init__(
        self,
        llm: LocalLLM,
        prompt_builder: SQLPromptBuilder | None = None,
    ) -> None:
        self.llm = llm
        self.prompt_builder = (
            prompt_builder
            or SQLPromptBuilder()
        )

    def repair(
        self,
        question: str,
        sql: str,
        errors: tuple[str, ...],
        schema_context: str,
    ) -> SQLRepairResult:
        """Generate a corrected SQL query."""

        if not question.strip():
            raise ValueError(
                "Question cannot be empty."
            )

        if not sql.strip():
            raise ValueError(
                "SQL query cannot be empty."
            )

        if not errors:
            raise ValueError(
                "At least one validation error is required."
            )

        if not schema_context.strip():
            raise ValueError(
                "Schema context cannot be empty."
            )

        prompt = self._build_repair_prompt(
            question=question,
            sql=sql,
            errors=errors,
            schema_context=schema_context,
        )

        response = self.llm.generate(prompt)

        repaired_sql = self._clean_sql(
            response.text
        )

        if not repaired_sql:
            raise RuntimeError(
                "The LLM returned an empty repaired SQL query."
            )

        return SQLRepairResult(
            question=question,
            original_sql=sql,
            repaired_sql=repaired_sql,
            model_name=response.model_name,
        )

    def _build_repair_prompt(
        self,
        question: str,
        sql: str,
        errors: tuple[str, ...],
        schema_context: str,
    ) -> str:
        """Build the repair prompt."""

        metric_definitions = (
            self.prompt_builder.METRIC_DEFINITIONS
        )

        error_text = "\n".join(
            f"- {error}"
            for error in errors
        )

        return (
            f"{self.REPAIR_INSTRUCTIONS}\n\n"
            f"{metric_definitions}\n\n"
            "DATABASE SCHEMA:\n"
            f"{schema_context}\n\n"
            "USER QUESTION:\n"
            f"{question.strip()}\n\n"
            "PREVIOUS SQL:\n"
            f"{sql.strip()}\n\n"
            "VALIDATION ERRORS:\n"
            f"{error_text}\n\n"
            "CORRECTED SQL:"
        )

    @staticmethod
    def _clean_sql(text: str) -> str:
        """Remove common Markdown formatting from LLM output."""

        sql = text.strip()

        if sql.startswith("```sql"):
            sql = sql[6:]

        elif sql.startswith("```"):
            sql = sql[3:]

        if sql.endswith("```"):
            sql = sql[:-3]

        return sql.strip()